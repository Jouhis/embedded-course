const uint8_t *font_glyph(char c) {
    for (size_t i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); i++) {
        if (GLYPHS[i].c == c) {
            return GLYPHS[i].cols;
        }
    }
    return GLYPHS[0].cols;   // index 0 is the space glyph
}
